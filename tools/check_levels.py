# ------------------------------------------------------------------ validation + ore placement
def validate(num, g, seed):
    h, w = len(g), len(g[0])
    probs = []
    for i, r in enumerate(g):
        if len(r) != w: probs.append(f"row {i} len {len(r)}")
    if w % W or h % H: probs.append(f"size {w}x{h}")
    at = lambda c, r: '#' if r < 0 or c < 0 or r >= h or c >= w else g[r][c]
    solid = lambda t: t in '#WL'
    free = lambda c, r: at(c, r) not in '#L'
    P = next((c, r) for r, row in enumerate(g) for c, ch in enumerate(row) if ch == 'P')
    X = next((c, r) for r, row in enumerate(g) for c, ch in enumerate(row) if ch == 'X')
    if solid(at(P[0], P[1] - 1)): probs.append('start has no headroom')
    if not solid(at(X[0], X[1] + 1)): probs.append('miner not on the floor')
    seen = {P}; q = deque([P])
    while q:
        c, r = q.popleft()
        for nc, nr, need in [(c + 1, r, [(c + 1, r), (c + 1, r - 1)]), (c - 1, r, [(c - 1, r), (c - 1, r - 1)]),
                             (c, r - 1, [(c, r - 2)]), (c, r + 1, [(c, r + 1)])]:
            if all(free(a, b) for a, b in need) and (nc, nr) not in seen:
                seen.add((nc, nr)); q.append((nc, nr))
    if (X[0], X[1]) not in seen: probs.append('MINER UNREACHABLE')
    for r, row in enumerate(g):
        for c, ch in enumerate(row):
            if ch in 'BSMTX' and solid(ch): probs.append(f'entity in rock {c},{r}')
            if ch == 'S' and not any(solid(at(c, rr)) for rr in range(r - 1, r - 4, -1)): probs.append(f'spider without ceiling {c},{r}')
            if ch == 'M' and not (free(c, r - 1) and free(c, r + 1)): probs.append(f'moth cramped {c},{r}')
    # automatic ore placement: side-exposed (laser) or floor-exposed (dynamite), reachable, spread out
    rng = random.Random(seed)
    side, floor = [], []
    for r in range(1, h - 1):
        for c in range(w):
            if at(c, r) != '#': continue
            if any(free(c + d, r) and free(c + d, r + 1) and (c + d, r + 1) in seen for d in (-1, 1)): side.append((c, r))
            if free(c, r - 1) and free(c, r - 2) and (c, r - 1) in seen: floor.append((c, r))
    used = []
    def pick(cands, n):
        out = []; tries = 0
        while len(out) < n and tries < 2000 and cands:
            tries += 1; c, r = rng.choice(cands)
            if any(abs(c - a) + abs(r - b) < 5 for a, b in used): continue
            used.append((c, r)); out.append((c, r))
        return out
    rooms = (w // W) * (h // H)
    gold = pick(side, max(2, rooms)) + pick(floor, 1)
    copper = pick(side, rooms + 2) + pick(floor, 2)
    ores = [[c, r, 'g'] for c, r in gold] + [[c, r, 'c'] for c, r in copper]
    print(f"L{num}: {w}x{h} ({w // W}x{h // H} rooms), miner reachable={not any('UNREACH' in p for p in probs)}, ores={len(ores)}, problems={probs}")
    return not probs, ores

if __name__ == '__main__':
    ok = True; out = {}
    for n, g in LEVELS.items():
        good, ores = validate(n, g, 1000 + n)
        ok &= good; out[n] = {'map': g, 'ores': ores}
    json.dump(out, open('new_levels.json', 'w'))
    print('ALL OK' if ok else 'PROBLEMS')
